// =============================================================================
// WebSocket Gateway — the realtime half of the hybrid architecture.
// Implements Discord's gateway protocol:
//   • Auth via ?token=<JWT> query string on the HTTP upgrade request
//     (WS handshakes can't carry Authorization headers reliably).
//   • op10 HELLO with heartbeat_interval immediately on connect.
//   • op2 IDENTIFY / op6 RESUME (session_id + last seq → replay missed events).
//   • op1 HEARTBEAT ⇄ op11 HEARTBEAT_ACK; missing ACK ⇒ server closes socket
//     so the client rebuilds the connection (detects silent firewall drops).
//   • op3 PRESENCE_UPDATE, op4 VOICE_STATE_UPDATE, op7 RECONNECT.
//   • The gateway NEVER reads/writes the database. It subscribes to Redis
//     pub/sub (`channel:<id>` / `guild:<id>` / `user:<id>`) and relays DISPATCH
//     frames generated by the REST layer after persistence.
// =============================================================================
import { WebSocketServer } from 'ws';
import crypto from 'node:crypto';
import { verifyJwt } from '../lib/jwt.js';
import { subscribe } from '../cache/redis.js';

export const OPCODES = Object.freeze({
  DISPATCH: 0, HEARTBEAT: 1, IDENTIFY: 2, PRESENCE_UPDATE: 3,
  VOICE_STATE_UPDATE: 4, RESUME: 6, RECONNECT: 7, REQUEST_GUILD_MEMBERS: 8,
  INVALID_SESSION: 9, HELLO: 10, HEARTBEAT_ACK: 11,
});

const HEARTBEAT_INTERVAL = Number(process.env.HEARTBEAT_INTERVAL || 41250); // ms, like Discord
const SESSION_TTL = 5 * 60_000; // keep resumable sessions for 5 minutes

/** sessionId -> { userId, seq, events:[{seq,t,d}] ring buffer, guildIds:Set, channelIds:Set } */
const resumableSessions = new Map();

function pruneSessions() {
  const now = Date.now();
  for (const [id, s] of resumableSessions) if (now - s.updated > SESSION_TTL) resumableSessions.delete(id);
}
setInterval(pruneSessions, 60_000).unref?.();

export function createGateway(httpServer) {
  const wss = new WebSocketServer({ server: httpServer, path: '/ws' });

  wss.on('connection', (ws, req) => {
    // ---- 1. Authenticate BEFORE accepting the session -----------------------
    const url = new URL(req.url, 'http://localhost');
    const user = verifyJwt(url.searchParams.get('token'));
    if (!user) return ws.close(4001, 'Unauthorized'); // invalid token in query string

    const state = {
      userId: String(user.uid),
      identified: false,
      sessionId: null,
      seq: 0,
      awaitingAck: false,
      hbTimer: null,
      guildIds: new Set(),
      channelIds: new Set(),
      voiceChannel: null,
    };

    const send = (op, d = null, evt = null, seq = null) => {
      if (ws.readyState !== ws.OPEN) return;
      ws.send(JSON.stringify(seq != null ? { op, t: evt, s: seq, d } : { op, d }));
    };

    // ---- 2. HELLO (op10) -----------------------------------------------------
    send(OPCODES.HELLO, { heartbeat_interval: HEARTBEAT_INTERVAL });

    // Server-side watchdog: if a heartbeat goes unanswered within 2 intervals,
    // consider the connection dead (silent drop behind NAT/firewall).
    const watchdog = setInterval(() => {
      if (state.awaitingAck) {
        clearInterval(watchdog);
        ws.terminate(); // force client reconnect flow (exponential backoff)
      }
    }, HEARTBEAT_INTERVAL * 2);

    const dispatchToSocket = (event, data) => {
      state.seq += 1;
      const sess = resumableSessions.get(state.sessionId);
      if (sess) { sess.events.push({ seq: state.seq, t: event, d: data }); sess.updated = Date.now(); }
      send(OPCODES.DISPATCH, data, event, state.seq);
    };

    /** Subscribe this socket's session to a Redis pub/sub key for live relay. */
    const attachRelay = async (key) => {
      await subscribe(key, (evt) => {
        if (evt.t === 'PRESENCE_UPDATE' && String(evt.d.user?.id) === state.userId) return; // echo guard
        dispatchToSocket(evt.t, evt.d);
      });
    };

    ws.on('message', async (raw) => {
      let msg; try { msg = JSON.parse(raw); } catch { return ws.close(4002, 'Decode error'); }
      const { op, d } = msg;

      switch (op) {
        // ---- HEARTBEAT (op1): answer with ACK (op11) ------------------------
        case OPCODES.HEARTBEAT:
          state.awaitingAck = false;
          send(OPCODES.HEARTBEAT_ACK);
          break;

        // ---- IDENTIFY (op2) --------------------------------------------------
        case OPCODES.IDENTIFY: {
          const tokenUser = verifyJwt(d?.token);
          if (!tokenUser || String(tokenUser.uid) !== state.userId)
            return send(OPCODES.INVALID_SESSION, true), ws.close(4004, 'Authentication failed');
          state.sessionId = crypto.randomUUID();
          state.identified = true;
          resumableSessions.set(state.sessionId, {
            userId: state.userId, seq: 0, events: [], updated: Date.now(),
          });
          send(OPCODES.DISPATCH, { v: 9, session_id: state.sessionId }, 'READY', ++state.seq);

          // Join every guild/channel the user belongs to → Redis relays
          const guildKeys = await import('../db/index.js').then(({ db }) => {
            for (const m of db.tables.guild_members.filter((x) => String(x.user_id) === state.userId)) {
              state.guildIds.add(String(m.guild_id));
            }
            for (const c of db.find('channels', (ch) => !ch.guild_id || state.guildIds.has(String(ch.guild_id)))) {
              if (c.type === 'dm' || c.type === 'group_dm') state.channelIds.add(String(c.id));
            }
            return [...state.guildIds, ...state.channelIds];
          });
          for (const k of guildKeys) await attachRelay(k.startsWith('g') ? `guild:${k}` : `channel:${k}`);
          break;
        }

        // ---- RESUME (op6): restore session & replay missed events -----------
        case OPCODES.RESUME: {
          const sess = resumableSessions.get(d?.session_id);
          const tokenUser = verifyJwt(d?.token);
          if (!sess || !tokenUser || sess.userId !== state.userId) {
            send(OPCODES.INVALID_SESSION, false); // not resumable → full re-IDENTIFY
            return ws.close(4009, 'Session no longer valid');
          }
          state.sessionId = d.session_id;
          state.identified = true;
          send(OPCODES.DISPATCH, { resumed: true }, 'RESUMED', ++state.seq);
          for (const ev of sess.events) {
            if (ev.seq > Number(d.seq ?? 0)) {
              state.seq = ev.seq;
              send(OPCODES.DISPATCH, ev.d, ev.t, ev.seq); // replay gap-free stream
            }
          }
          break;
        }

        // ---- PRESENCE_UPDATE (op3): status online/idle/dnd/invisible --------
        case OPCODES.PRESENCE_UPDATE: {
          const status = ['online', 'idle', 'dnd', 'invisible'].includes(d?.status) ? d.status : 'online';
          const { setPresence } = await import('../cache/redis.js');
          await setPresence(state.userId, status, d?.activities?.[0] ?? null);
          await (await import('../cache/redis.js')).publish(`user:${state.userId}`, {
            t: 'PRESENCE_UPDATE', d: { user: { id: state.userId }, status, activities: d?.activities ?? [] },
          });
          send(OPCODES.HEARTBEAT_ACK); // lightweight ack of receipt
          break;
        }

        // ---- VOICE_STATE_UPDATE (op4): WebRTC signaling entrypoint ----------
        case OPCODES.VOICE_STATE_UPDATE: {
          // Relay SDP/ICE offer-answer negotiation is carried as CUSTOM events
          // between participants; media itself flows via the SFU (Mediasoup/LiveKit),
          // never through this gateway.
          const prev = state.voiceChannel;
          state.voiceChannel = d?.channel_id ? String(d.channel_id) : null;
          const { publish } = await import('../cache/redis.js');
          if (prev) await publish(`channel:${prev}`, { t: 'VOICE_CHANNEL_STATUS_UPDATE', d: { channel_id: prev, user_id: state.userId, left: true } });
          if (state.voiceChannel) {
            await attachRelay(`channel:${state.voiceChannel}`);
            await publish(`channel:${state.voiceChannel}`, {
              t: 'VOICE_STATE_UPDATE',
              d: { channel_id: state.voiceChannel, user_id: state.userId, self_mute: !!d.self_mute, self_deaf: !!d.self_deaf },
            });
          }
          break;
        }

        // ---- TYPING via WS (also allowed over REST POST /typing) ------------
        case 0: // inbound DISPATCH-style custom payloads (typing, ping...)
          if (msg.t === 'TYPING_START') {
            const { markTyping, publish } = await import('../cache/redis.js');
            await markTyping(msg.d.channel_id, state.userId);
            await publish(`channel:${msg.d.channel_id}`, { t: 'TYPING_START', d: { channel_id: msg.d.channel_id, user_id: state.userId } });
          }
          break;

        case OPCODES.RECONNECT:
          send(OPCODES.RECONNECT);
          setTimeout(() => ws.close(4000, 'Reconnect requested'), 100);
          break;

        default:
          ws.close(4002, 'Unknown opcode');
      }
    });

    ws.on('pong', () => { state.awaitingAck = false; });

    // Keep-alive ping frames at the transport level too (belt & suspenders)
    state.hbTimer = setInterval(() => {
      if (ws.readyState === ws.OPEN) {
        state.awaitingAck = true;
        ws.ping();
      }
    }, HEARTBEAT_INTERVAL);

    ws.on('close', () => {
      clearInterval(state.hbTimer); clearInterval(watchdog);
      // Presence flips offline only when no other sockets remain for this user
      // (rebuildable from active connections — docs §2.3).
    });
  });

  return wss;
}
